package viewpoint.render;
/** Stable optional character-core capability, backed only by the selected Native pack. */
public final class AimohGf2SourceHost {
    public static String profileKey(int a,int b){AimohNativeGf2Runtime.prepareData();return AimohNativeGf2Registry.active()?AimohNativeGf2Registry.profileKey(a,b):null;}
    public static String modelDescriptor(String key,int a,int b,int vertices,int materials){return AimohNativeGf2Registry.modelDescriptor(key,a,b,vertices,materials);}
    public static byte[] resourceBytes(String key,String path)throws java.io.IOException{return AimohNativeGf2Registry.resourceBytes(key,path);}
    private AimohGf2SourceHost(){}
}
