from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / 'game/mod/42/media'


def read(path):
    return json.loads(path.read_text('utf-8-sig'))


def catalog_source():
    registry = read(MEDIA / 'aimoh_pmx/registry.json')
    catalog = read(MEDIA / 'ui/AimohPMXReadyRoom/catalog.json')
    rows = ['-- Generated by tools/generate_multiplayer_catalog.py.', 'return {']
    for pack, ids in sorted(registry['packs'].items()):
        cards = read(ROOT / f'game/packs/{pack}/42/media/ui/AimohPMXReadyRoom/packs/{pack}.json')['models']
        for model in sorted(ids):
            if model not in cards or model not in catalog['models']:
                continue
            meta = cards[model]
            character = meta['character']
            pool = catalog['roomRecruitment'].get(character, {}).get('pool', pack)
            draw = model in catalog['roomOutfitPools']
            free = (meta.get('included') or meta.get('isDefault')
                    or model == catalog['roomStarterSkins'].get(character))
            price = 0 if free or draw else catalog['roomOutfitPrices'].get(model, 1080)
            mod = registry['pack_mod_ids'][pack]
            rows.append(f'    ["{model}"] = {{ mod = "{mod}", character = "{pool}", '
                        f'outfitDraw = {str(draw).lower()}, price = {price} }},')
    return '\n'.join([*rows, '}', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = MEDIA / 'lua/shared/GFL2MultiplayerCatalog.lua'
    expected = catalog_source()
    if args.check:
        if target.read_text('utf8') != expected:
            raise SystemExit('Multiplayer catalog is stale. Run this tool without --check.')
        print('PASS multiplayer catalog matches framework and character packs')
    else:
        target.write_text(expected, 'utf8', newline='\n')
